const dicts: Record<Lang, Dict> = { "zh-TW": zh, en, id, vi, tl, th, ja, ko, es, fr };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s = dicts[lang]?.[key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function isLang(x: string | undefined | null): x is Lang {
  return !!x && LANGS.some((l) => l.code === x);
}

export function pickLang(cookie?: string, accept?: string | null): Lang {
  if (isLang(cookie)) return cookie;
  const a = (accept || "").toLowerCase();
  for (const part of a.split(",")) {
    const tag = part.split(";")[0].trim();
    if (tag.startsWith("zh")) return "zh-TW";
    if (tag.startsWith("id") || tag.startsWith("in")) return "id";
    if (tag.startsWith("vi")) return "vi";
    if (tag.startsWith("tl") || tag.startsWith("fil")) return "tl";
    if (tag.startsWith("th")) return "th";
    if (tag.startsWith("ja")) return "ja";
    if (tag.startsWith("ko")) return "ko";
    if (tag.startsWith("es")) return "es";
    if (tag.startsWith("fr")) return "fr";
    if (tag.startsWith("en")) return "en";
  }
  return "zh-TW";
}

